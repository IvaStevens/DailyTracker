import React, { useState } from 'react'
import type { PR, ReviewIssue } from '../types/tracker'

const REVIEW_SECTION_MAP: Record<string, string> = {
  'security':     'Security Issue',
  'performance':  'Performance Issue',
  'code quality': 'Code Quality',
  'laravel':      'Pattern Violation',
  'vue':          'Pattern Violation',
  'ux':           'UX/Accessibility Issue',
  'suggestion':   'Suggestion',
}

function parseReviewIssues(text: string): ReviewIssue[] {
  const issues: ReviewIssue[] = []
  let currentSection = 'Issue'
  let idx = 0

  for (const rawLine of text.split('\n')) {
    const hMatch = rawLine.match(/^###\s+(.+)/)
    if (hMatch) {
      const hLow = hMatch[1].toLowerCase()
      for (const [key, val] of Object.entries(REVIEW_SECTION_MAP)) {
        if (hLow.includes(key)) { currentSection = val; break }
      }
      continue
    }

    const m = rawLine.match(/^[`\s]*\[?(CRITICAL|HIGH|MEDIUM|LOW)\]?\s+(.+?)[`\s]*$/i)
    if (!m) continue

    const [, severity, rest] = m
    const fl = rest.match(/^(\S+):(\d+)\s+[—–-]+\s+(.+)$/)
    issues.push({
      id:          `rv_issue_${idx++}`,
      severity,
      sectionType: currentSection,
      file:        fl ? fl[1] : null,
      line:        fl ? parseInt(fl[2], 10) : null,
      description: fl ? fl[3].trim() : rest.trim(),
      rawLine,
    })
  }
  return issues
}

const SEV_RE = /\[(CRITICAL|HIGH|MEDIUM|LOW)\]|\b(CRITICAL|HIGH|MEDIUM|LOW)\b/g

function ReviewLine({ line, issue, checked, onCheck }: {
  line:    string
  issue:   ReviewIssue | undefined
  checked: boolean
  onCheck: (id: string, v: boolean) => void
}) {
  const parts: React.ReactNode[] = []
  let last = 0

  for (const m of line.matchAll(SEV_RE)) {
    const word    = m[1] || m[2]
    const label   = m[1] ? `[${word}]` : word
    if (m.index! > last) parts.push(line.slice(last, m.index))
    parts.push(<span key={m.index} className={`rv-sev rv-${word.toLowerCase()}`}>{label}</span>)
    last = m.index! + m[0].length
  }
  if (last < line.length) parts.push(line.slice(last))

  return (
    <div className={`rv-line${issue ? ' rv-issue-line' : ''}`}>
      {issue && (
        <input
          type="checkbox"
          className="rv-issue-cb"
          checked={checked}
          onChange={e => onCheck(issue.id, e.target.checked)}
          onClick={e => e.stopPropagation()}
        />
      )}
      <span>{parts}</span>
    </div>
  )
}

function ReviewMarkdown({ text, issueMap, checked, onCheck }: {
  text:     string
  issueMap: Map<string, ReviewIssue>
  checked:  Set<string>
  onCheck:  (id: string, v: boolean) => void
}) {
  return (
    <div className="review-text">
      {text.split('\n').map((line, i) => {
        if (line.startsWith('## ')) return <div key={i} className="rv-header">{line.slice(3)}</div>
        if (/^[-•]\s/.test(line)) {
          const rest = line.slice(2)
          const parts: React.ReactNode[] = []
          let last = 0
          for (const m of rest.matchAll(SEV_RE)) {
            const word  = m[1] || m[2]
            const label = m[1] ? `[${word}]` : word
            if (m.index! > last) parts.push(rest.slice(last, m.index))
            parts.push(<span key={m.index} className={`rv-sev rv-${word.toLowerCase()}`}>{label}</span>)
            last = m.index! + m[0].length
          }
          if (last < rest.length) parts.push(rest.slice(last))
          return <div key={i} className="rv-bullet">• {parts}</div>
        }
        if (line.trim() === '') return <div key={i} className="rv-gap" />
        const issue = issueMap.get(line)
        return (
          <ReviewLine
            key={i}
            line={line}
            issue={issue}
            checked={!!issue && checked.has(issue.id)}
            onCheck={onCheck}
          />
        )
      })}
    </div>
  )
}

interface Props {
  pr:           PR
  running:      boolean
  cached:       string | null
  onRun:        (pr: PR) => void
  onCommented?: () => void
}

export default function ReviewPanel({ pr, running, cached, onRun, onCommented }: Props) {
  const [checked,    setChecked]    = useState<Set<string>>(new Set())
  const [sendStatus, setSendStatus] = useState<'idle' | 'sending' | 'sent' | 'failed'>('idle')

  function onCheck(id: string, v: boolean) {
    setChecked(prev => {
      const next = new Set(prev)
      v ? next.add(id) : next.delete(id)
      return next
    })
  }

  async function send(issues: ReviewIssue[]) {
    const toSend = issues.filter(i => checked.has(i.id))
    if (toSend.length === 0) return
    setSendStatus('sending')

    const lines = toSend.map(issue =>
      `${issue.sectionType}: [${issue.severity}] ${issue.file ? `${issue.file}:${issue.line} — ` : ''}${issue.description}`
    )
    const body = `${lines.join('\n\n')}\n\n[Comment Auto-generated by Claude]`

    const result = await window.tracker.postPrReviewComment(pr.number, pr.repo, body)
    if (!result?.error) {
      setSendStatus('sent')
      setChecked(new Set())
      window.tracker.markPrCommented(pr.url)
      onCommented?.()
      setTimeout(() => setSendStatus('idle'), 2500)
    } else {
      console.error('[ReviewPanel] send failed:', result.error)
      setSendStatus('failed')
    }
  }

  if (running) {
    return (
      <div className="review-panel">
        <div className="review-running">Claude is reviewing this PR…</div>
      </div>
    )
  }

  if (!cached) {
    return (
      <div className="review-panel">
        <div className="review-empty-msg">Claude hasn't reviewed this PR yet.</div>
        <button className="review-run-btn" onClick={() => onRun(pr)}>Review with Claude</button>
      </div>
    )
  }

  const issues   = parseReviewIssues(cached)
  const issueMap = new Map(issues.map(i => [i.rawLine, i]))

  return (
    <div className="review-panel">
      <ReviewMarkdown text={cached} issueMap={issueMap} checked={checked} onCheck={onCheck} />

      {issues.length > 0 && (
        <div className="rv-send-wrap">
          <button
            className="rv-send-btn"
            disabled={checked.size === 0 || sendStatus === 'sending'}
            onClick={() => send(issues)}
          >
            {sendStatus === 'sending' ? 'Sending…'
              : sendStatus === 'sent'    ? 'Sent ✓'
              : sendStatus === 'failed'  ? 'Failed'
              : 'Send Selected'}
          </button>
        </div>
      )}

      <button className="review-rerun-btn" onClick={() => onRun(pr)}>↻ Re-review</button>
    </div>
  )
}
